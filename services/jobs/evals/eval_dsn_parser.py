import sys
import os
import hypothesis.strategies as st
from hypothesis import given, settings
from unittest.mock import patch

# Add services directory to path
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '../..')))
from jobs.daily_transit_aggregation import get_db_connection

# Generate complex passwords that contain all sorts of special characters
password_strategy = st.text(alphabet=st.characters(blacklist_categories=('Cs',)), min_size=1)

@settings(max_examples=100)
@given(password=password_strategy)
def test_eval_dsn_generalization(password):
    # Construct a valid DSN using a complex password generated by Hypothesis
    # We urlencode it to simulate what standard tools might do, but wait - 
    # the user's issue is UNENCODED passwords with '@'. So we test unencoded.
    dsn = f"postgresql://test_user:{password}@db.server.com:5432/test_db"
    
    with patch('jobs.daily_transit_aggregation.psycopg2.connect') as mock_connect:
        get_db_connection(dsn)
        
        call_kwargs = mock_connect.call_args.kwargs
        
        # If the parsing worked, the password should match exactly
        assert call_kwargs.get('password') == password
        assert call_kwargs.get('user') == 'test_user'
        assert call_kwargs.get('host') == 'db.server.com'

if __name__ == "__main__":
    print("Running DSN Parser Eval with Hypothesis...")
    test_eval_dsn_generalization()
    print("Eval completed successfully! The fix generalizes to 100 randomly generated complex string passwords.")
